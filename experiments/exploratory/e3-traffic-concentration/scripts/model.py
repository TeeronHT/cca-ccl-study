def kmin_kb(rate_bps):
    return KMIN_KB_AT_200G * rate_bps // GPU_RATE_BPS


def kmax_kb(rate_bps):
    return KMAX_KB_AT_200G * rate_bps // GPU_RATE_BPS


def ecn_rates():
    """Bitrates that actually appear: host links plus the three uplink rates."""
    rates = {GPU_RATE_BPS}
    for _token, bps in FABRIC_UPLINK.values():
        rates.add(bps)
    return tuple(sorted(rates))
