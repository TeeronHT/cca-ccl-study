def rack_of(rank):
    return rank // GPUS_PER_RACK


def _ring_edges(group, clockwise):
    edges = []
    for index, src in enumerate(group):
        step = 1 if clockwise else -1
        edges.append((src, group[(index + step) % len(group)]))
    return edges


def _dim0_groups():
    return [tuple(range(base, base + 4)) for base in range(0, N_GPU, 4)]


def _dim1_groups():
    return [tuple(range(base, N_GPU, 4)) for base in range(4)]


def _pair(src, dst, messages, msg_bytes, phase):
    return {
        "src": src,
        "dst": dst,
        "messages": messages,
        "msg_bytes": msg_bytes,
        "bytes": messages * msg_bytes,
        "cross_rack": rack_of(src) != rack_of(dst),
        "phase": phase,
    }


def schedule(collective):
    """Directed pairs actually generated by ASTRA for one 64 MiB AllReduce.

    ring16: one clockwise Ring AllReduce per 16 MiB chunk. Reduce-scatter and
    all-gather are the two halves of that single phase, both to rank+1.
    Four chunks run one at a time.

    ring44: per chunk, and strictly in this order:
      reduce-scatter on dimension 0, clockwise, 4 MiB
      ring all-reduce on dimension 1, clockwise, 1 MiB
      all-gather on dimension 0, anticlockwise, 4 MiB
    Dimension 0 and dimension 1 of adjacent chunks can overlap because they
    use different queues. The two directions on dimension 0 cannot.
    """
    if collective == "ring16":
        msg = CHUNK_BYTES // N_GPU  # 1 MiB
        steps = 2 * (N_GPU - 1)  # 30
        messages = steps * SPLITS  # 120
        pairs = [
            _pair(rank, (rank + 1) % N_GPU, messages, msg, "allreduce")
            for rank in range(N_GPU)
        ]
        simultaneous = 1
    elif collective == "ring44":
        # Reduce-scatter: 16 MiB / 4 ranks, 3 steps, 4 chunks.
        rs_msg = CHUNK_BYTES // 4  # 4 MiB
        rs_messages = 3 * SPLITS  # 12
        # All-reduce on the reduced 4 MiB: msg = 1 MiB, 6 steps, 4 chunks.
        ar_msg = (CHUNK_BYTES // 4) // 4  # 1 MiB
        ar_messages = (2 * (4 - 1)) * SPLITS  # 24
        # All-gather of the 4 MiB result: 3 steps, 4 chunks.
        ag_msg = CHUNK_BYTES // 4  # 4 MiB
        ag_messages = 3 * SPLITS  # 12
        pairs = []
        for group in _dim0_groups():
            for src, dst in _ring_edges(group, True):
                pairs.append(_pair(src, dst, rs_messages, rs_msg, "reduce-scatter"))
            for src, dst in _ring_edges(group, False):
                pairs.append(_pair(src, dst, ag_messages, ag_msg, "all-gather"))
        for group in _dim1_groups():
            for src, dst in _ring_edges(group, True):
                pairs.append(_pair(src, dst, ar_messages, ar_msg, "allreduce"))
        simultaneous = 4
    else:
        raise KeyError(collective)
    total_messages = sum(pair["messages"] for pair in pairs)
    total_bytes = sum(pair["bytes"] for pair in pairs)
    cross_pairs = [pair for pair in pairs if pair["cross_rack"]]
    same_pairs = [pair for pair in pairs if not pair["cross_rack"]]
    return {
        "collective": collective,
        "pairs": pairs,
        "messages": total_messages,
        "total_bytes": total_bytes,
        "per_rank_bytes": total_bytes // N_GPU,
        "same_rack_bytes": sum(pair["bytes"] for pair in same_pairs),
        "cross_rack_bytes": sum(pair["bytes"] for pair in cross_pairs),
        "cross_rack_pairs": len(cross_pairs),
        "directed_pairs": len(pairs),
        "simultaneous_cross_rack_flows_per_rack": simultaneous,
    }


